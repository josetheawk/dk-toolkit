"""dk doc-lint: keep docs small, portable, and linked correctly.

Rules (thresholds come from dk.toml [docs]):
  - each playbook file and the playbook as a whole stay under their line budgets
  - AGENTS.md stays under its budget
  - no project-specific term appears in the playbook (it must transfer as-is)
  - every relative markdown link points at an existing file
  - every file in the generated-docs dir carries GENERATED_MARK on line 1
"""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path

from .command import MISMATCH, OK, Command, hint
from .config import Config

GENERATED_MARK = "<!-- generated by dk"
_LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
_EXTERNAL = ("http://", "https://", "mailto:", "#")


@dataclass(frozen=True, order=True)
class Problem:
    path: str
    line: int
    message: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.message}"


def _excluded(cfg: Config, path: Path) -> bool:
    return any(path.is_relative_to(e) for e in cfg.docs.exclude)


def markdown_files(cfg: Config) -> list[Path]:
    files = [p for p in cfg.root.rglob("*.md") if not _excluded(cfg, p) and ".git" not in p.parts]
    return sorted(files)


def _line_count(path: Path) -> int:
    return len(path.read_text().splitlines())


def budget_usage(cfg: Config) -> list[tuple[str, int, int]]:
    """(label, used, limit) rows for the budgeted docs."""
    d = cfg.docs
    rows = []
    playbook_files = sorted(d.playbook.rglob("*.md")) if d.playbook.is_dir() else []
    total = 0
    for f in playbook_files:
        n = _line_count(f)
        total += n
        rows.append((cfg.rel(f), n, d.playbook_file_lines))
    rows.append((f"{cfg.rel(d.playbook)}/ (total)", total, d.playbook_total_lines))
    if d.agents_md.is_file():
        rows.append((cfg.rel(d.agents_md), _line_count(d.agents_md), d.agents_md_lines))
    return rows


def lint(cfg: Config) -> list[Problem]:
    problems: list[Problem] = []
    d = cfg.docs

    for label, used, limit in budget_usage(cfg):
        if used > limit:
            problems.append(Problem(label.split()[0], 0, f"{used} lines, budget {limit}"))

    banned = [(t, re.compile(rf"(?<![A-Za-z0-9]){re.escape(t)}(?![A-Za-z0-9])", re.I)) for t in d.banned_in_playbook]
    if d.playbook.is_dir():
        for f in sorted(d.playbook.rglob("*")):
            if not f.is_file():
                continue
            for i, line in enumerate(f.read_text(errors="replace").splitlines(), 1):
                for term, rx in banned:
                    if rx.search(line):
                        problems.append(Problem(cfg.rel(f), i, f"project-specific term {term!r} in playbook"))

    for f in markdown_files(cfg):
        for i, line in enumerate(f.read_text().splitlines(), 1):
            for target in _LINK.findall(line):
                if target.startswith(_EXTERNAL):
                    continue
                path_part = target.split("#", 1)[0]
                if not path_part:
                    continue
                dest = (cfg.root / path_part.lstrip("/")) if path_part.startswith("/") else (f.parent / path_part)
                if not dest.exists():
                    problems.append(Problem(cfg.rel(f), i, f"broken link {target}"))

    if d.generated.is_dir():
        for f in sorted(d.generated.rglob("*.md")):
            first = f.read_text().split("\n", 1)[0]
            if not first.startswith(GENERATED_MARK):
                problems.append(Problem(cfg.rel(f), 1, f"generated doc without {GENERATED_MARK!r} header"))

    return sorted(set(problems))


def run(cfg: Config, args: argparse.Namespace) -> int:
    problems = lint(cfg)
    for p in problems:
        print(p)
    if problems:
        print(f"doc-lint: {len(problems)} problem(s)")
        return MISMATCH
    print("doc-lint: OK")
    hint("status")
    return OK


COMMAND = Command("doc-lint", "docs", "check doc budgets, playbook portability, links, generated headers", run)
