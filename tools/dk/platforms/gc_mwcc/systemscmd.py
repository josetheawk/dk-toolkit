"""dk systems: progress per game system (camera, collision, physics, ...), for planning work by what it touches.

Systems are regexes in dk.toml `[platform.systems]` (name = "pattern"). A function belongs to every system whose
pattern matches its unit name or its own (mangled) name, so `game/unk` code is placed by its class and function
names. Per system: code, exact share, near (80-99.99%) share, open functions and unwritten ones (0%), and the
largest open functions. Writes docs/generated/systems.md; `--json` for scripts.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from ...core.command import OK, USAGE, Command, hint
from ...core.config import Config
from ...core.progress import load_report

TOP = 8


def classify(report: dict, systems: dict[str, str]) -> dict[str, dict]:
    pats = {k: re.compile(v) for k, v in systems.items()}
    out = {k: {"code": 0, "exact": 0, "near": 0, "units": set(), "open": []} for k in systems}
    for u in report.get("units", []):
        for f in u.get("functions", []):
            size, pct = int(f.get("size", 0) or 0), float(f.get("fuzzy_match_percent") or 0.0)
            for k, p in pats.items():
                if not (p.search(u["name"]) or p.search(f["name"])):
                    continue
                s = out[k]
                s["code"] += size
                s["units"].add(u["name"])
                if pct >= 100.0:
                    s["exact"] += size
                else:
                    s["near"] += size if pct >= 80.0 else 0
                    s["open"].append({"unit": u["name"], "function": f["name"], "size": size, "percent": round(pct, 2)})
    for s in out.values():
        s["units"] = sorted(s["units"])
        s["open"].sort(key=lambda r: -r["size"])
    return out


def render(res: dict[str, dict]) -> list[str]:
    lines = ["<!-- generated by dk systems; do not edit -->", "# Progress per game system", "",
             "A function counts in every system whose `[platform.systems]` pattern (dk.toml) matches its unit or its "
             "own name. Exact: byte-identical. Near: 80-99.99%. Unwritten: 0%.", "",
             "| system | units | code | exact | near | open | unwritten |", "|---|---|---|---|---|---|---|"]
    for k, s in res.items():
        c = max(s["code"], 1)
        unwritten = sum(1 for r in s["open"] if r["percent"] == 0.0)
        lines.append(f"| {k} | {len(s['units'])} | {s['code'] / 1024:.0f} KB | {s['exact'] / c:.0%} | {s['near'] / c:.0%} "
                     f"| {len(s['open'])} | {unwritten} |")
    for k, s in res.items():
        if not s["open"]:
            continue
        lines += ["", f"## {k}: largest open functions", ""]
        lines += [f"- `{r['function']}` ({r['unit']}, {r['size']} B, {r['percent']:.2f}%)" for r in s["open"][:TOP]]
        unwritten = [r for r in s["open"] if r["percent"] == 0.0]
        if unwritten:
            lines.append(f"- unwritten: {', '.join('`' + r['function'] + '`' for r in unwritten[:TOP])}"
                         + (f" and {len(unwritten) - TOP} more" if len(unwritten) > TOP else ""))
    return lines


def run(cfg: Config, args: argparse.Namespace) -> int:
    systems = cfg.platform_options.get("systems") or {}
    if not systems:
        print("error: no [platform.systems] in dk.toml (name = \"regex on unit or function names\")")
        return USAGE
    report = load_report(cfg)
    if report is None:
        print("error: no objdiff report yet (./dk build)")
        return USAGE
    res = classify(report, systems)
    lines = render(res)
    out = cfg.root / "docs" / "generated" / "systems.md"
    out.write_text("\n".join(lines) + "\n")
    if args.json:
        Path(args.json).write_text(json.dumps(res, indent=1) + "\n")
    print("\n".join(lines[5:5 + 2 + len(res)]))
    print(f"written to {cfg.rel(out)}")
    hint("card FN...  (cards for a system's open functions)")
    return OK


def _configure(p: argparse.ArgumentParser) -> None:
    p.add_argument("--json", help="also write the per-system result (units, open functions) here")


COMMAND = Command("systems", "analysis", "progress per game system (dk.toml [platform.systems] patterns)", run, _configure)
