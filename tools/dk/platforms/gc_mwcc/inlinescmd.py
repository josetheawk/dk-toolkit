    p.add_argument("--repeats", action="store_true",
                   help="self-repeat mode: stretches of the function that occur again inside it with the same shape "
                        "and the same callees and literals (an inline called twice)")
    p.add_argument("--census", action="store_true", help="with --repeats: coverage of every open function (writes census.json)")
    p.add_argument("--calibrate", action="store_true",
                   help="with --repeats: precision/recall against matched functions, negative and shuffled controls")
    p.add_argument("--refresh", action="store_true", help="--calibrate: recompile the units for the ground truth")
    p.add_argument("--shape-only", action="store_true", help="--repeats: skip the identity check (ablation)")
    p.add_argument("--no-values", action="store_true", help="--repeats: skip the value check (ablation)")
    p.add_argument("--scan", action="store_true",
                   help="inline-boundary fingerprints (zero copied, field re-read, an exact function's body) in the "
                        "target asm of every open function, biggest bytes at stake first; frozen functions skipped")
    p.add_argument("--unit", help="with --scan: one unit's open functions")
    p.add_argument("--only", metavar="FN[,FN]", help="with --scan: these functions, exact or not (replay; each is left "
                                                     "out of the exact-body pool)")
