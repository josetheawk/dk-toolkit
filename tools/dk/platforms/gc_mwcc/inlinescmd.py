    p.add_argument("--min-conf", type=float, default=inlines.MIN_CONF, help="matched / unfolded weight to accept")
    p.add_argument("--jobs", type=int, default=0, help="worker processes (default: dk.toml [platform] jobs, DK_JOBS, "
                                                       "else the cores the machine leaves idle, at most 8)")


