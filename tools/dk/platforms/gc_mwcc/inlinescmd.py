"""dk inlines <fn | unit | --giants>: which inlined helpers a big function is made of.

For each target: copies of known functions found on value-numbered code (inlines.py), each with
its source file, the binding of its parameters (this = sp+0x26c) and the call to write; then
stretches that repeat in the giants but match no known function (helper candidates, cut where
the partner copies change). Shares are of the body; the frame is counted separately.

`--giants` decodes every unmatched function of 2 KB or more; `--write` records the summary in
docs/generated/inlines.md; `--json PATH` writes everything for tools. `--scan` lists inline-boundary
fingerprints in every open function's target asm (inlinescan.py).
"""

from __future__ import annotations

import argparse
import json
import multiprocessing
import os
from dataclasses import dataclass, field
from pathlib import Path

from ...core.command import OK, USAGE, Command, hint
from ...core.config import Config
