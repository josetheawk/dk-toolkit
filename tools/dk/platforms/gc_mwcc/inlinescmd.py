from . import asmflow, asmindex, inlines
from .asmflow import describe
from .demangle import demangle
from .dol import Dol
from .dtk_symbols import is_auto_name, read_symbols

GIANT = 0x800
MIN_SIZE = 0x100          # unit targets: functions smaller than this are not decoded


# ---------------------------------------------------------------- context

@dataclass
class Helper:
    name: str
    unit: str | None          # source path under src/ (None: not declared yet)
    exact: bool
    same: list[str] = field(default_factory=list)    # functions with identical code

    @property
    def rank(self) -> tuple:
        return (not self.exact, is_auto_name(self.name), self.name)


@dataclass
class Context:
    cfg: Config
    entries: dict
    unit_of_file: dict[Path, str | None]
    exact: set[str]
    sizes: dict[str, int]
    canon: object

    def unit(self, name: str) -> str | None:
        e = self.entries.get(name)
        return self.unit_of_file.get(e.file) if e else None


def load_context(cfg: Config) -> Context | None:
    opts = cfg.platform_options
    asm_dir = cfg.root / opts["asm"]
    if not asm_dir.is_dir() or not cfg.report.is_file() or not cfg.original.is_file():
        return None
    entries = {n: e for n, e in asmindex.index(asmindex.current_asm_files(cfg)).items() if e.kind == "fn"}
    build = cfg.root / "build" / cfg.game_id
    unit_of_file: dict[Path, str | None] = {}
    config_json = build / "config.json"
    if config_json.is_file():
        for u in json.loads(config_json.read_text()).get("units", []):
            rel = (cfg.root / u["object"]).relative_to(build / "obj").with_suffix(".s")
            unit_of_file[asm_dir / rel] = None if u.get("autogenerated") else u["name"]
    report = json.loads(cfg.report.read_text())
    exact, sizes = set(), {}
    for u in report.get("units", []):
        for f in u.get("functions", []):
            sizes[f["name"]] = int(f.get("size", 0))
            if f.get("fuzzy_match_percent") == 100.0:
                exact.add(f["name"])
    symbols = {s.name: (s.section, s.address, s.size) for s in read_symbols(cfg.root / opts["symbols"])}
    dol = Dol.parse(cfg.original.read_bytes())
    return Context(cfg, entries, unit_of_file, exact, sizes, inlines.literal_canon(symbols, dol.read))


def prepared(ctx: Context, name: str) -> inlines.Prepared:
    flow = asmflow.flow_of(name, ctx.entries[name].text)
    return inlines.prepare(inlines.canonicalize(flow, ctx.canon))


def build_pool(ctx: Context, exclude: set[str], min_weight: int, max_weight: int):
    """Templates: every function small enough to be inlined, identical code kept once (exact
    and named functions first)."""
    groups: dict[tuple, list[str]] = {}
    for name in sorted(ctx.entries):
        text = ctx.entries[name].text
        if name in exclude or text.count("\n") > 4 * max_weight + 40:
            continue
        sig = tuple((i.mnem, tuple("L" if o.startswith((".L_", '".L_')) else o for o in i.ops))
                    for i in asmflow.parse_insns(text))
        groups.setdefault(sig, []).append(name)
    templates: dict[str, inlines.Prepared] = {}
    helpers: dict[str, Helper] = {}
    for names in groups.values():
        hs = sorted((Helper(n, ctx.unit(n), n in ctx.exact) for n in names), key=lambda h: h.rank)
        rep = hs[0]
        p = prepared(ctx, rep.name)
        if not (min_weight <= p.static_weight <= max_weight) or not p.anchors:
            continue
        rep.same = [h.name for h in hs[1:]]
        templates[rep.name] = p
        helpers[rep.name] = rep
    return templates, helpers


def giants(ctx: Context) -> list[str]:
    return sorted(n for n, s in ctx.sizes.items() if s >= GIANT and n not in ctx.exact and n in ctx.entries)


def unit_targets(ctx: Context, unit: str) -> list[str]:
    unit = unit.removeprefix("src/")
    files = [f for f, u in ctx.unit_of_file.items() if u == unit or (u and u.rsplit(".", 1)[0] == unit)]
    return sorted(n for n, e in ctx.entries.items() if e.file in files and n not in ctx.exact
                  and ctx.sizes.get(n, len(e.text.splitlines()) * 4) >= MIN_SIZE)


# ---------------------------------------------------------------- decoding one function

_WORK: dict = {}          # set before forking workers


def _decode(name: str) -> dict:
    w = _WORK
    ctx, templates, helpers, opts = w["ctx"], w["templates"], w["helpers"], w["opts"]
    g = w["preps"][name]
    nodes = g.flow.nodes
    excl = {name}
    rank = (lambda t: helpers[t].rank) if helpers else None
    copies = inlines.find_copies({k: v for k, v in templates.items() if k not in excl}, g,
                                 min_weight=opts["min_weight"], min_conf=opts["min_conf"],
                                 max_weight=opts["max_weight"], rank=rank)
    frame = set(g.frame)
    claimed: dict[int, bool] = {}            # node -> claimed by an exact helper
    for m in copies:
        for i in m.claims:
            if i not in frame:
                claimed[i] = claimed.get(i, False) or helpers[m.template].exact
    seqs = w["seqs"]
    blocks = inlines.check_blocks(inlines.repeated_blocks(name, w["tokens"], w["index"]), w["preps"], seqs)
    repeated: set[int] = set()
    block_rows = []
    for b in blocks:
        for sg in b.segments:
            if sg.verified < inlines.BLOCK_CHECK:
                continue
            own = set(seqs[name][sg.start:sg.end])
            for i in list(own):
                own |= g.feeders.get(i, set())
            new = {i for i in own if i not in claimed and i not in frame}
            if len(new) < opts["min_block"]:
                continue
            repeated |= new
            partners = []
            for other, d in sg.partners:
                pos = sg.start + d
                if 0 <= pos < len(seqs[other]):
                    partners.append([other, w["preps"][other].flow.nodes[seqs[other][pos]].addr])
            block_rows.append({
                "start": nodes[seqs[name][sg.start]].addr, "end": nodes[seqs[name][sg.end - 1]].addr + 4,
                "insns": sg.end - sg.start, "new": len(new), "copies": len(sg.partners),
                "partners": partners[:8], "verified": round(sg.verified, 2)})
    body = len(nodes) - len(frame)
    exact_n = sum(1 for v in claimed.values() if v)
    by_helper: dict[str, list] = {}
    for m in copies:
        by_helper.setdefault(m.template, []).append(m)
    rows = []
    for t, ms in sorted(by_helper.items(), key=lambda kv: (-len(set().union(*(m.claims for m in kv[1]))), kv[0])):
        h = helpers[t]
        rows.append({
            "helper": t, "pretty": pretty(t), "unit": h.unit, "exact": h.exact, "same": h.same[:5],
            "weight": templates[t].static_weight, "insns": len(set().union(*(m.claims for m in ms)) - frame),
            "copies": [{"start": nodes[m.span[0]].addr, "score": f"{m.matched}/{m.total}",
                        "bind": {_reg(k): show(v, g.flow) for k, v in sorted(m.bind.items(), key=lambda kv: str(kv[0]))
                                 if k[0] in ("arg", "sp")},
                        "call": call_text(t, m.bind, g.flow)} for m in ms]})
    return {
        "function": name, "unit": ctx.unit(name), "size": ctx.sizes.get(name, len(nodes) * 4),
        "insns": len(nodes), "frame": len(frame), "body": body,
        "copies_exact": exact_n, "copies_open": len(claimed) - exact_n, "repeated": len(repeated),
        "helpers": rows, "blocks": sorted(block_rows, key=lambda r: r["start"])}


def _reg(root: tuple) -> str:
    return root[1] if root[0] == "arg" else "own stack"


def show(v, flow) -> str:
    """A target value in words: sp+0x26c, 0x503, &sym, or what an instruction produced."""
    root, off = v
    if root[0] == "n":
        n = flow.nodes[root[1]]
        what = "result of " + n.key if n.kind == "call" else f"{n.mnem}@{n.addr:08X}"
        return what + (f"+{off:#x}" if off else "")
    if root[0] == "sp" and off == 0:
        return "sp"
    return describe(v)


def pretty(name: str) -> str:
    f = demangle(name)
    if f is None:
        return name
    cls = "::".join(f.quals)
    last = f.quals[-1] if f.quals else ""
    method = {"ctor": last, "dtor": "~" + last}.get(f.name, f.name)
    params = ", ".join(p.text for p in f.params)
    return f"{cls + '::' if cls else ''}{method}({params}){' const' if f.const else ''}"


def call_text(name: str, bind: dict, flow) -> str:
    """The call to write for one copy: parameters from the binding, ? where the compiler folded
    the parameter away (its value only fed compares the copy no longer has)."""
    f = demangle(name)
    gpr, fpr = iter(asmflow.ARG_GPRS), iter(asmflow.ARG_FPRS)
    args: list[tuple[str, str | None]] = []
    if f is None:
        regs = sorted((k[1] for k in bind if k[0] == "arg"), key=lambda r: asmflow.ARG_REGS.index(r))
        args = [(r, r) for r in regs]
        label = name
    else:
        label = pretty(name).split("(")[0]
        if f.quals:
            args.append(("this", next(gpr, None)))
        for p in f.params:
            reg = next(fpr, None) if p.reg == "fpr" else next(gpr, None) if p.reg == "gpr" else None
            args.append((p.text, reg))
    shown = []
    for label_, reg in args:
        b = bind.get(("arg", reg)) if reg else None
        val = show((b[0], b[1]), flow) if b else "?"
        shown.append(f"this={val}" if label_ == "this" else val)
    return f"{label}({', '.join(shown)})"


# ---------------------------------------------------------------- running

def decode_all(ctx: Context, targets: list[str], opts: dict, jobs: int) -> list[dict]:
    corpus = sorted(set(giants(ctx)) | set(targets))
    preps = {n: prepared(ctx, n) for n in corpus}
    seqs = {n: inlines.block_sequence(p) for n, p in preps.items()}
    tokens = {n: [inlines.token(preps[n].flow.nodes[i]) for i in s] for n, s in seqs.items()}
    templates, helpers = build_pool(ctx, set(targets), opts["min_weight"], opts["max_weight"])
    _WORK.update(ctx=ctx, templates=templates, helpers=helpers, opts=opts, preps=preps, seqs=seqs,
                 tokens=tokens, index=inlines.kgram_index(tokens))
    # biggest first so the slow ones start early; results come back in target order
    order = sorted(targets, key=lambda n: -len(preps[n].flow.nodes))
    if jobs > 1 and len(targets) > 1:
        with multiprocessing.get_context("fork").Pool(min(jobs, len(targets))) as pool:
            done = dict(zip(order, pool.map(_decode, order, chunksize=1)))
    else:
        done = {n: _decode(n) for n in order}
    return [done[n] for n in targets]


def _pct(part: int, whole: int) -> str:
    return f"{100.0 * part / whole:.1f}%" if whole else "-"


def render_one(r: dict, limit: int) -> list[str]:
    body = r["body"]
    copies = r["copies_exact"] + r["copies_open"]
    unexplained = body - copies - r["repeated"]
    unit = f"src/{r['unit']}" if r["unit"] else "unit not declared"
    out = [f"# {r['function']}  {unit}  {r['size']:#x} bytes ({r['insns']} insns, frame {r['frame']})",
           f"explained {_pct(copies + r['repeated'], body)} of the body: copies {_pct(copies, body)} "
           f"(of exact helpers {_pct(r['copies_exact'], body)}, open {_pct(r['copies_open'], body)}), "
           f"repeated blocks {_pct(r['repeated'], body)}; unexplained {_pct(unexplained, body)}"]
    if r["helpers"]:
        out.append("\n## copies of known functions (inline them: write the call, the compiler expands it)")
    for h in r["helpers"][:limit]:
        state = "exact" if h["exact"] else "open"
        src = f"src/{h['unit']}" if h["unit"] else "unit not declared"
        same = f"; same code: {', '.join(h['same'])}" if h["same"] else ""
        out.append(f"- {h['pretty']}  [{h['helper']}, {src}, {state}]  {len(h['copies'])}x, "
                   f"{h['insns']} insns{same}")
        for c in h["copies"][:limit]:
            out.append(f"    {c['start']:08X} {c['score']:>7}  {c['call']}")
        if len(h["copies"]) > limit:
            out.append(f"    … {len(h['copies']) - limit} more (--limit, --json)")
    if len(r["helpers"]) > limit:
        out.append(f"… {len(r['helpers']) - limit} more helpers (--limit, --json)")
    blocks = r["blocks"]
    if blocks:
        out.append("\n## repeated blocks no known function explains (helper candidates; cut where the copies change)")
    for b in sorted(blocks, key=lambda b: (-b["new"] * b["copies"], b["start"]))[:limit]:
        where = ", ".join(f"{n}@{a:08X}" for n, a in b["partners"][:3])
        out.append(f"- {b['start']:08X}..{b['end']:08X}  {b['insns']} insns ({b['new']} new), "
                   f"{b['copies']} other copies: {where}{' …' if b['copies'] > 3 else ''}")
    return out


def summary(results: list[dict], top: int = 10) -> list[str]:
    body = sum(r["body"] for r in results)
    exact = sum(r["copies_exact"] for r in results)
    open_ = sum(r["copies_open"] for r in results)
    rep = sum(r["repeated"] for r in results)
    frame = sum(r["frame"] for r in results)
    size = sum(r["size"] for r in results)
    out = [f"{len(results)} functions, {size} bytes: frame {4 * frame} bytes; of the {4 * body} body bytes "
           f"{_pct(exact + open_ + rep, body)} explained: copies {_pct(exact + open_, body)} "
           f"(exact helpers {_pct(exact, body)}, open {_pct(open_, body)}), repeated blocks {_pct(rep, body)}",
           "", "| function | unit | bytes | copies | repeated | unexplained | main helpers |", "|---|---|---|---|---|---|---|"]
    for r in sorted(results, key=lambda r: (-r["size"], r["function"])):
        b = r["body"]
        c = r["copies_exact"] + r["copies_open"]
        main = ", ".join(f"{h['pretty'].split('(')[0]} ×{len(h['copies'])}" for h in r["helpers"][:2])
        out.append(f"| {r['function']} | {r['unit'] or '-'} | {r['size']} | {_pct(c, b)} | {_pct(r['repeated'], b)} "
                   f"| {_pct(b - c - r['repeated'], b)} | {main or '-'} |")
    helpers: dict[str, list] = {}
    for r in results:
        for h in r["helpers"]:
            e = helpers.setdefault(h["helper"], [h, 0, 0, 0])
            e[1] += len(h["copies"])
            e[2] += h["insns"]
            e[3] += 1
    out += ["", f"Helpers that explain the most bytes (top {top}): match these first, every copy then comes free.", "",
            "| helper | function | source | state | copies | in functions | bytes |", "|---|---|---|---|---|---|---|"]
    for name, (h, n, insns, fns) in sorted(helpers.items(), key=lambda kv: (-kv[1][2], kv[0]))[:top]:
        out.append(f"| {h['pretty']} | {name} | {h['unit'] or '-'} | {'exact' if h['exact'] else 'open'} | {n} "
                   f"| {fns} | {4 * insns} |")
    return out


def run(cfg: Config, args: argparse.Namespace) -> int:
    ctx = load_context(cfg)
    if ctx is None:
        print("error: needs the disassembly, the objdiff report and the original binary")
        hint("build")
        return USAGE
    if args.census or args.calibrate:
        return run_repeat_measures(cfg, ctx, args)
    if args.scan:
        return run_scan(cfg, ctx, args)
    if args.giants:
        targets = giants(ctx)
    elif args.target in ctx.entries:
        targets = [args.target]
    elif args.target:
        targets = unit_targets(ctx, args.target)
        if not targets:
            print(f"error: {args.target!r} is neither a function nor a unit with open functions of "
                  f"{MIN_SIZE:#x} bytes or more")
            return USAGE
    else:
        print("error: give a function, a unit, or --giants")
        return USAGE
    if args.repeats:
        return run_repeats(ctx, targets, args)
    opts = {"min_weight": args.min_weight, "max_weight": args.max_weight, "min_conf": args.min_conf,
            "min_block": inlines.KGRAM}
    from .jobs import resolve
    results = decode_all(ctx, targets, opts, resolve(args.jobs, cfg, cap=8))
    if args.json:
        Path(args.json).write_text(json.dumps(results, indent=1, sort_keys=True) + "\n")
    if len(results) == 1:
        print("\n".join(render_one(results[0], args.limit)))
    else:
        if not args.giants:
            for r in results:
                print("\n".join(render_one(r, args.limit)) + "\n")
        print("\n".join(summary(results)))
    if args.write and args.giants:
        doc = cfg.docs.generated / "inlines.md"
        doc.write_text("\n".join([f"{GENERATED_MARK} inlines --giants --write; do not edit -->",
                                  "# Inline helpers inside the giant functions", "",
                                  "Unmatched functions of 2 KB or more, decoded by `./dk inlines`: copies of known "
                                  "functions (on value-numbered code) and repeated blocks. Shares are of the body; "
                                  "the frame is counted apart. Details per function: `./dk inlines <fn>`.", ""]
                                 + summary(results)) + "\n")
        print(f"wrote {cfg.rel(doc)}")
    first = max(results, key=lambda r: (r["size"], r["function"]))["function"] if results else ""
    hint(f"inlines {first}" if args.giants else f"ctx {first}", "gen --harvest")
    return OK


def run_scan(cfg: Config, ctx: Context, args: argparse.Namespace) -> int:
    """--scan: inline-boundary fingerprints in the target asm of every open function (inlinescan.py)."""
    from . import inlinescan
    from .jobs import resolve
    pct: dict[str, float] = {}
    report = json.loads(cfg.report.read_text())
    for u in report.get("units", []):
        for f in u.get("functions", []):
            pct[f["name"]] = float(f.get("fuzzy_match_percent") or 0.0)
    frozen = inlinescan.frozen_names(cfg)
    if args.only:
        targets = [n for n in args.only.split(",") if n in ctx.entries]
        ctx.exact = ctx.exact - set(targets)          # replay: each as if still open
    else:
        targets = [n for n, s in ctx.sizes.items() if n not in ctx.exact and n in ctx.entries and n in pct]
        if args.unit or args.target:
            u = (args.unit or args.target).removeprefix("src/")
            targets = [n for n in targets if (ctx.unit(n) or "") in (u, ) or (ctx.unit(n) or "").rsplit(".", 1)[0] == u]
    targets = sorted(n for n in targets if n not in frozen)
    if not targets:
        print("error: no open, unfrozen functions to scan")
        return USAGE
    rows = inlinescan.scan(ctx, targets, pct, resolve(args.jobs, cfg, cap=8), bodies=not args.no_bodies)
    if args.diff:
        inlinescan.mark_divergence(rows, scan_diffs(cfg, ctx, [r for r in rows if r["flagged"]]))
    if args.json:
        inlinescan.write_json(args.json, rows)
    print("\n".join(inlinescan.render(rows, args.limit)))
    hits = [r for r in rows if r["flagged"]]
    from ...core.usage import note
    note(scanned=len(rows), flagged=len(hits),
         functions=[r["function"] for r in sorted(hits, key=lambda r: -r["at_stake"])[:30]])
    if hits:
        hint(f"inlines {max(hits, key=lambda r: r['at_stake'])['function']}")
    return OK


def scan_diffs(cfg: Config, ctx: Context, rows: list[dict]) -> dict[str, list[int]]:
    """function -> target offsets where ours differs, one objdiff run per unit with a source."""
    from . import inlinescan
    from .matching import load_objdiff_units
    from .route import unit_diff
    wanted = {r["unit"].rsplit(".", 1)[0] for r in rows if r["unit"]}
    names = {r["function"] for r in rows}
    out: dict[str, list[int]] = {}
    for u in load_objdiff_units(cfg):
        src = u.get("metadata", {}).get("source_path", "").removeprefix("src/").rsplit(".", 1)[0]
        if not u.get("base_path") or src not in wanted:
            continue
        pairs, _ = unit_diff(cfg, u)
        for name, (t, o) in pairs.items():
            if name in names:
                out[name] = inlinescan.diverging_offsets(t, o)
    return out


def run_repeats(ctx: Context, targets: list[str], args: argparse.Namespace) -> int:
    """--repeats: stretches that occur again inside one function, same shape and same relocation targets."""
    from . import repeats
    rows = []
    for name in targets:
        p = prepared(ctx, name)
        rep = repeats.analyze(name, p, ctx.canon, identity=not args.shape_only, values=not args.no_values)
        rows.append((name, p, rep))
        if len(targets) == 1 or not rep.repeats:
            if len(targets) == 1:
                print(f"# {name}: {rep.size} instructions, {len(rep.repeats)} repeated blocks cover "
                      f"{rep.covered()} ({_pct(rep.covered(), rep.size)}), {rep.covered(True)} beyond the first copies")
        else:
            print(f"# {name}: {len(rep.repeats)} blocks cover {_pct(rep.covered(), rep.size)} of {rep.size} instructions")
        for r in sorted(rep.repeats, key=lambda r: (-r.length * len(r.starts), r.starts[0]))[:args.limit]:
            where = ", ".join(f"{rep.addrs[s]:08X}" for s in r.starts[:8])
            print(f"- {r.length} insns x{len(r.starts)} (values {r.verified:.2f}"
                  f"{f', {r.dropped} dropped' if r.dropped else ''}): {where}{' ...' if len(r.starts) > 8 else ''}")
    if args.json:
        Path(args.json).write_text(json.dumps([{"function": n, "size": r.size, "repeats": [
            {"length": x.length, "verified": x.verified, "copies": [f"{r.addrs[s]:08X}" for s in x.starts]}
            for x in r.repeats]} for n, _p, r in rows], indent=1) + "\n")
    hint("inlines --repeats --census")
    return OK


def run_repeat_measures(cfg: Config, ctx: Context, args: argparse.Namespace) -> int:
    from . import repeatcal
    from .jobs import resolve
    jobs = resolve(args.jobs, cfg, cap=4)
    out = cfg.root / repeatcal.OUT
    out.mkdir(parents=True, exist_ok=True)
    if args.census:
        doc = repeatcal.census(ctx, jobs)
        (out / "census.json").write_text(json.dumps(doc))
        print(f"{doc['open_functions']} open functions ({doc['open_bytes']} bytes without {', '.join(doc['skipped'])}): "
              f"repeated self-blocks cover {100 * doc['coverage']:.1f}% (beyond the first copies "
              f"{100 * doc['redundant_coverage']:.1f}%); giants {100 * doc['giant_coverage']:.1f}%; "
              f"{doc['functions_with_repeats']} functions have one\n")
        print("\n".join(repeatcal.census_table(doc, args.limit if args.limit != 12 else 20)))
        print("\nUncalibrated: run --calibrate for the false-block rate on functions with no inline called twice.")
        return OK
    truth = repeatcal.gather_truth(cfg, ctx.exact, jobs, force=args.refresh)
    cal = repeatcal.evaluate(ctx, truth, jobs)
    (out / "calibration.json").write_text(json.dumps(cal, indent=1))
    pop = cal["population"]
    print(f"population: {pop['positives']} positives, {pop['negatives']} negatives ({pop['small_inline_only']} functions "
          f"call a small inline twice, below the finder's floor); sample {cal['sample']}")
    for k in ("precision", "recall", "recall_novalue", "name_recall", "false_in_negatives", "shuffled",
              "swap_rejected", "swap_shape_still_reports"):
        print(f"{k}: {cal[k]}")
    return OK


