"""dk systems: a function counts in every system its unit or own name matches."""

import unittest

from tools.dk.platforms.gc_mwcc.systemscmd import classify, render

REPORT = {"units": [
    {"name": "main/game/camera/a", "functions": [{"name": "f", "size": 100, "fuzzy_match_percent": 100.0},
                                                 {"name": "g", "size": 50, "fuzzy_match_percent": 90.0}]},
    {"name": "main/game/unk/b", "functions": [{"name": "vf3__12CameraTargetFv", "size": 40, "fuzzy_match_percent": 0.0},
                                              {"name": "h", "size": 10, "fuzzy_match_percent": 100.0}]}]}


class SystemsTest(unittest.TestCase):
    def test_unit_or_function_name(self):
        res = classify(REPORT, {"camera": "game/camera/|Camera", "physics": "CameraTarget"})
        self.assertEqual((res["camera"]["code"], res["camera"]["exact"], res["camera"]["near"]), (190, 100, 50))
        self.assertEqual([r["function"] for r in res["camera"]["open"]], ["g", "vf3__12CameraTargetFv"])
        self.assertEqual(res["physics"]["code"], 40)
        md = "\n".join(render(res))
        self.assertTrue(md.startswith("<!-- generated by dk systems"))
        self.assertIn("unwritten: `vf3__12CameraTargetFv`", md)


if __name__ == "__main__":
    unittest.main()
